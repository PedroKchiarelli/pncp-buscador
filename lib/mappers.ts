import type { Contratacao } from '@/types/pncp';
import type { LicitacaoRow } from '@/types/db';

// Converte uma linha do Supabase → formato da API PNCP (usado no frontend)
export function rowToContratacao(row: LicitacaoRow): Contratacao {
  return {
    srp:                               row.srp,
    anoCompra:                         row.ano_compra ?? 0,
    sequencialCompra:                  row.sequencial_compra ?? 0,
    numeroControlePNCP:                row.numero_controle_pncp,
    numeroCompra:                      row.numero_compra ?? '',
    processo:                          row.processo ?? '',
    objetoCompra:                      row.objeto_compra,
    informacaoComplementar:            row.informacao_complementar,
    dataInclusao:                      row.data_inclusao ?? '',
    dataPublicacaoPncp:                row.data_publicacao_pncp ?? '',
    dataAtualizacao:                   row.data_atualizacao ?? '',
    dataAberturaProposta:              row.data_abertura_proposta ?? '',
    dataEncerramentoProposta:          row.data_encerramento_proposta ?? '',
    modalidadeId:                      row.modalidade_id ?? 0,
    modalidadeNome:                    row.modalidade_nome ?? '',
    situacaoCompraId:                  row.situacao_compra_id ?? 0,
    situacaoCompraNome:                row.situacao_compra_nome ?? '',
    modoDisputaId:                     row.modo_disputa_id ?? 0,
    modoDisputaNome:                   row.modo_disputa_nome ?? '',
    tipoInstrumentoConvocatorioCodigo: row.tipo_instrumento_codigo ?? 0,
    tipoInstrumentoConvocatorioNome:   row.tipo_instrumento_nome ?? '',
    valorTotalEstimado:                row.valor_total_estimado,
    valorTotalHomologado:              row.valor_total_homologado,
    usuarioNome:                       row.usuario_nome ?? '',
    linkSistemaOrigem:                 row.link_sistema_origem,
    linkProcessoEletronico:            row.link_processo_eletronico,
    justificativaPresencial:           row.justificativa_presencial,
    emendaParlamentar:                 row.emenda_parlamentar,
    fontesOrcamentarias:               [],
    orgaoEntidade: {
      cnpj:        row.orgao_cnpj ?? '',
      razaoSocial: row.orgao_razao_social ?? '',
      poderId:     row.orgao_poder_id ?? '',
      esferaId:    row.orgao_esfera_id ?? '',
    },
    unidadeOrgao: {
      ufNome:        row.uf_nome ?? '',
      codigoUnidade: row.codigo_unidade ?? '',
      nomeUnidade:   row.nome_unidade ?? '',
      ufSigla:       row.uf_sigla ?? '',
      municipioNome: row.municipio_nome ?? '',
      codigoIbge:    row.codigo_ibge ?? '',
    },
    amparoLegal: {
      descricao: row.amparo_legal_descricao ?? '',
      nome:      row.amparo_legal_nome ?? '',
      codigo:    row.amparo_legal_codigo ?? 0,
    },
  };
}

// Converte um objeto Contratacao (API PNCP) → linha para upsert no Supabase
