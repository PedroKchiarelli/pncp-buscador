    numero_controle_pncp:       c.numeroControlePNCP,
    srp:                        c.srp,
    ano_compra:                 c.anoCompra,
    sequencial_compra:          c.sequencialCompra,
    numero_compra:              c.numeroCompra || null,
    processo:                   c.processo || null,
    objeto_compra:              c.objetoCompra,
    informacao_complementar:    c.informacaoComplementar,
    data_inclusao:              c.dataInclusao || null,
    data_publicacao_pncp:       c.dataPublicacaoPncp || null,
    data_atualizacao:           c.dataAtualizacao || null,
    data_abertura_proposta:     c.dataAberturaProposta || null,
    data_encerramento_proposta: c.dataEncerramentoProposta || null,
    modalidade_id:              c.modalidadeId,
    modalidade_nome:            c.modalidadeNome,
    situacao_compra_id:         c.situacaoCompraId,
    situacao_compra_nome:       c.situacaoCompraNome,
    modo_disputa_id:            c.modoDisputaId,
    modo_disputa_nome:          c.modoDisputaNome,
    tipo_instrumento_codigo:    c.tipoInstrumentoConvocatorioCodigo,
    tipo_instrumento_nome:      c.tipoInstrumentoConvocatorioNome,
    valor_total_estimado:       c.valorTotalEstimado,
    valor_total_homologado:     c.valorTotalHomologado,
    usuario_nome:               c.usuarioNome || null,
    link_sistema_origem:        c.linkSistemaOrigem,
    link_processo_eletronico:   c.linkProcessoEletronico,
    justificativa_presencial:   c.justificativaPresencial,
    emenda_parlamentar:         c.emendaParlamentar,
    orgao_cnpj:                 c.orgaoEntidade.cnpj || null,
    orgao_razao_social:         c.orgaoEntidade.razaoSocial || null,
    orgao_poder_id:             c.orgaoEntidade.poderId || null,
    orgao_esfera_id:            c.orgaoEntidade.esferaId || null,
    uf_sigla:                   c.unidadeOrgao.ufSigla || null,
